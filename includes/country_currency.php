function normalizeCountryKey(string $s): string
{
    $s = strtolower(trim($s));
    $s = str_replace(['-', '_'], ' ', $s);
    $s = preg_replace('/[^a-z ]/', '', $s);
    $s = preg_replace('/\s+/', ' ', $s);
    // "Kingdom of Saudi Arabia", "Federal Republic of Germany", "People's Republic of China" …
    $s = preg_replace('/^(the )?(federal republic of|peoples republic of|republic of|kingdom of|state of|sultanate of) /', '', $s);
    return trim($s);
}

/** @return array{country:string,currency:string}|null */
function resolveWorksite(string $input): ?array
{
    $key = normalizeCountryKey($input);
    if ($key === '') return null;

    foreach (COUNTRY_CURRENCY as $name => $code) {
        if (normalizeCountryKey($name) === $key) {
            return ['country' => $name, 'currency' => $code];
        }
    }
    $alias = COUNTRY_ALIASES[$key] ?? null;
    if ($alias !== null && isset(COUNTRY_CURRENCY[$alias])) {
        return ['country' => $alias, 'currency' => COUNTRY_CURRENCY[$alias]];
    }
    return null;
}
